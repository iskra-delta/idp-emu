static const char *crt_vert_src = R"(
#version 330 core
layout(location = 0) in vec2 aPos;
layout(location = 1) in vec2 aTexCoord;
out vec2 TexCoord;
void main() {
    gl_Position = vec4(aPos, 0.0, 1.0);
    TexCoord = aTexCoord;
}
)";

static const char *crt_frag_src = R"(
#version 330 core
in vec2 TexCoord;
out vec4 FragColor;

uniform sampler2D screen_texture;
uniform vec2 resolution;

void main() {
    vec2 uv = TexCoord;

    // Barrel distortion (CRT curvature)
    vec2 cc = uv - 0.5;
    float r2 = dot(cc, cc);
    uv = cc * (1.0 + 0.06 * r2 + 0.04 * r2 * r2) + 0.5;

    // Outside screen = black (rounded corners)
    if (uv.x < 0.0 || uv.x > 1.0 || uv.y < 0.0 || uv.y > 1.0) {
        FragColor = vec4(0.0, 0.0, 0.0, 1.0);
        return;
    }

    // Sample pixel
    float pixel = texture(screen_texture, uv).r;

    // Bloom (soft glow from nearby lit pixels)
    float bloom = 0.0;
    vec2 texel = 1.0 / resolution;
    for (int i = -2; i <= 2; i++) {
        for (int j = -2; j <= 2; j++) {
            bloom += texture(screen_texture, uv + vec2(float(i), float(j)) * texel).r;
        }
    }
    bloom /= 25.0;

    // Green phosphor (Matsushita P1-style)
    vec3 color = vec3(0.10, 0.90, 0.20) * pixel;
    color += vec3(0.05, 0.30, 0.10) * bloom * 0.4;

    // Scanlines
    float scanline = sin(uv.y * resolution.y * 3.14159265) * 0.5 + 0.5;
    color *= 0.80 + 0.20 * scanline;

    // Vignette (darker edges)
    vec2 vig = uv * (1.0 - uv);
    color *= clamp(pow(vig.x * vig.y * 15.0, 0.20), 0.0, 1.0);

    // Ambient CRT glass glow
    color += vec3(0.003, 0.008, 0.003);

    FragColor = vec4(color, 1.0);
}
)";

void display::init()
{
    // Source texture (monochrome composited image, single channel)
    glGenTextures(1, &source_tex_);
    glBindTexture(GL_TEXTURE_2D, source_tex_);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, COMP_W, COMP_H, 0,
                 GL_RED, GL_UNSIGNED_BYTE, nullptr);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);

    // CRT output texture (RGBA, post-shader)
    glGenTextures(1, &crt_tex_);
    glBindTexture(GL_TEXTURE_2D, crt_tex_);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, COMP_W, COMP_H, 0,
                 GL_RGBA, GL_UNSIGNED_BYTE, nullptr);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);

    // Framebuffer object for CRT render pass
    glGenFramebuffers(1, &fbo_);
    glBindFramebuffer(GL_FRAMEBUFFER, fbo_);
    glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0,
                           GL_TEXTURE_2D, crt_tex_, 0);
    if (glCheckFramebufferStatus(GL_FRAMEBUFFER) != GL_FRAMEBUFFER_COMPLETE)
        std::cerr << "[error] CRT framebuffer incomplete\n";
    glBindFramebuffer(GL_FRAMEBUFFER, 0);

    // CRT shader
    shader_ = compile_shader(crt_vert_src, crt_frag_src);

    // Fullscreen quad (position + texcoord)
    float quad[] = {
        -1.0f, -1.0f, 0.0f, 0.0f,
         1.0f, -1.0f, 1.0f, 0.0f,
        -1.0f,  1.0f, 0.0f, 1.0f,
         1.0f,  1.0f, 1.0f, 1.0f,
    };
    glGenVertexArrays(1, &vao_);
    glGenBuffers(1, &vbo_);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glBufferData(GL_ARRAY_BUFFER, sizeof(quad), quad, GL_STATIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void *)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float),
                          (void *)(2 * sizeof(float)));
    glBindVertexArray(0);
}

void display::shutdown()
{
    if (shader_) glDeleteProgram(shader_);
    if (fbo_) glDeleteFramebuffers(1, &fbo_);
    if (source_tex_) glDeleteTextures(1, &source_tex_);
    if (crt_tex_) glDeleteTextures(1, &crt_tex_);
    if (vbo_) glDeleteBuffers(1, &vbo_);
    if (vao_) glDeleteVertexArrays(1, &vao_);
}

void display::update()
{
    composite();

    glBindTexture(GL_TEXTURE_2D, source_tex_);
    glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, COMP_W, COMP_H,
                    GL_RED, GL_UNSIGNED_BYTE, comp_);

    apply_crt();
}

void display::composite()
{
    for (int y = 0; y < COMP_H; y++)
    {
        int text_y = y / 2;
        for (int x = 0; x < COMP_W; x++)
        {
            uint8_t text_val = text_fb_[x + text_y * TEXT_W];

            uint8_t gfx_val = 0;
            int gx = x - GFX_X_OFF;
            int gy = y - GFX_Y_OFF;
            if (gx >= 0 && gx < GFX_W && gy >= 0 && gy < GFX_H)
                gfx_val = gfx_fb_[gx + gy * GFX_W];

            comp_[x + y * COMP_W] = (text_val || gfx_val) ? 255 : 0;
        }
    }
}

void display::apply_crt()
{
    // Save GL state
    GLint prev_fbo, prev_viewport[4];
    glGetIntegerv(GL_FRAMEBUFFER_BINDING, &prev_fbo);
    glGetIntegerv(GL_VIEWPORT, prev_viewport);

    // Render to CRT FBO
    glBindFramebuffer(GL_FRAMEBUFFER, fbo_);
    glViewport(0, 0, COMP_W, COMP_H);

    glUseProgram(shader_);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, source_tex_);
    glUniform1i(glGetUniformLocation(shader_, "screen_texture"), 0);
    glUniform2f(glGetUniformLocation(shader_, "resolution"),
                (float)COMP_W, (float)COMP_H);

    glBindVertexArray(vao_);
    glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
    glBindVertexArray(0);

    // Restore GL state
    glUseProgram(0);
    glBindFramebuffer(GL_FRAMEBUFFER, (GLuint)prev_fbo);
    glViewport(prev_viewport[0], prev_viewport[1],
               prev_viewport[2], prev_viewport[3]);
}

void display::set_text_pixel(int x, int y, bool on)
{
    if (x >= 0 && x < TEXT_W && y >= 0 && y < TEXT_H)
        text_fb_[x + y * TEXT_W] = on ? 255 : 0;
}

void display::set_gfx_pixel(int x, int y, bool on)
{
    if (x >= 0 && x < GFX_W && y >= 0 && y < GFX_H)
        gfx_fb_[x + y * GFX_W] = on ? 255 : 0;
}

void display::clear_text()
{
    memset(text_fb_, 0, sizeof(text_fb_));
}

void display::clear_gfx()
{
    memset(gfx_fb_, 0, sizeof(gfx_fb_));
}

