void display::draw_char(int col, int row, char c)
{
    if (col < 0 || col >= COLS || row < 0 || row >= ROWS)
        return;
    int idx = (unsigned char)c - 32;
    if (idx < 0 || idx >= 96)
        return;
    int x0 = col * CHAR_W;
    int y0 = row * CHAR_H + 3; // center 8px font in 13px cell
    for (int r = 0; r < 8; r++)
    {
        uint8_t bits = font_8x8[idx][r];
        for (int b = 0; b < 8; b++)
        {
            if (bits & (0x80 >> b))
                set_text_pixel(x0 + b, y0 + r, true);
        }
    }
}

void display::draw_text(int col, int row, const char *text)
{
    while (*text && col < COLS)
    {
        draw_char(col, row, *text);
        col++;
        text++;
    }
}

GLuint display::compile_shader(const char *vert_src, const char *frag_src)
{
    GLuint vs = glCreateShader(GL_VERTEX_SHADER);
    glShaderSource(vs, 1, &vert_src, nullptr);
    glCompileShader(vs);
    GLint ok;
    glGetShaderiv(vs, GL_COMPILE_STATUS, &ok);
    if (!ok)
    {
        char log[512];
        glGetShaderInfoLog(vs, sizeof(log), nullptr, log);
        std::cerr << "[error] Vertex shader: " << log << "\n";
    }

    GLuint fs = glCreateShader(GL_FRAGMENT_SHADER);
    glShaderSource(fs, 1, &frag_src, nullptr);
    glCompileShader(fs);
    glGetShaderiv(fs, GL_COMPILE_STATUS, &ok);
    if (!ok)
    {
        char log[512];
        glGetShaderInfoLog(fs, sizeof(log), nullptr, log);
        std::cerr << "[error] Fragment shader: " << log << "\n";
    }

    GLuint prog = glCreateProgram();
    glAttachShader(prog, vs);
    glAttachShader(prog, fs);
    glLinkProgram(prog);
    glGetProgramiv(prog, GL_LINK_STATUS, &ok);
    if (!ok)
    {
        char log[512];
        glGetProgramInfoLog(prog, sizeof(log), nullptr, log);
        std::cerr << "[error] Shader link: " << log << "\n";
    }

    glDeleteShader(vs);
    glDeleteShader(fs);
    return prog;
}
